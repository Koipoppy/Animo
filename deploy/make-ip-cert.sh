#!/usr/bin/env bash
# Issues the server certificate for a bare public IP (no domain, no ICP filing) and
# prepares the Caddy config. The Android app trusts certs signed by the bundled CA.
#
#   deploy/make-ip-cert.sh 1.2.3.4          # HTTPS on 8443 (default)
#   deploy/make-ip-cert.sh 1.2.3.4 443      # HTTPS on 443
#
# Outputs:
#   Backend/certs/animo-ca.crt         public CA (also copied into the app)
#   Backend/certs/server.crt / server.key   Caddy serves these
#   Backend/Caddyfile.ip                    generated reverse-proxy config
#   android/app/src/main/res/raw/animo_ca.crt
set -euo pipefail
export MSYS_NO_PATHCONV=1

IP="${1:-}"
PORT="${2:-8443}"
[ -n "$IP" ] || { echo "用法: deploy/make-ip-cert.sh <公网IP> [端口，默认8443]" >&2; exit 2; }
case "$IP" in
  *[!0-9.]*|.*|*.) echo "IP 格式不对：$IP" >&2; exit 2 ;;
esac
case "$PORT" in
  *[!0-9]*|"") echo "端口不对：$PORT" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/Backend/certs"
RAW="$ROOT/android/app/src/main/res/raw"
mkdir -p "$OUT" "$RAW"

# Work inside the certs directory so native Windows openssl never sees /d/... paths.
cd "$OUT"

if [ ! -f animo-ca.key ] || [ ! -f animo-ca.crt ]; then
  echo "== 生成私有 CA"
  openssl req -x509 -newkey rsa:4096 -sha256 -days 3650 -nodes \
    -keyout animo-ca.key -out animo-ca.crt \
    -subj "/CN=Animo Private CA/O=TeamChillpass/C=CN" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null \
    || { echo "生成 CA 失败" >&2; exit 1; }
  chmod 600 animo-ca.key
fi

echo "== 为 $IP 签发服务器证书（365 天）"
openssl req -newkey rsa:2048 -nodes -keyout server.key -out server.csr \
  -subj "/CN=$IP/O=TeamChillpass/C=CN" 2>/dev/null \
  || { echo "生成服务器 CSR 失败" >&2; exit 1; }
cat > server.ext <<EOF
subjectAltName=IP:$IP
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
EOF
openssl x509 -req -in server.csr -CA animo-ca.crt -CAkey animo-ca.key \
  -CAcreateserial -out server.crt -days 365 -sha256 -extfile server.ext 2>/dev/null \
  || { echo "签发服务器证书失败" >&2; exit 1; }
chmod 600 server.key

cd "$ROOT"
cp "$OUT/animo-ca.crt" "$RAW/animo_ca.crt"

if [ "$PORT" = "443" ]; then ADDR="https://$IP"; else ADDR="https://$IP:$PORT"; fi
cat > "$ROOT/Backend/Caddyfile.ip" <<EOF
# Generated by deploy/make-ip-cert.sh — do not commit.
$ADDR {
	tls /certs/server.crt /certs/server.key
	encode gzip
	reverse_proxy api:8787
}
EOF

echo "== 完成"
echo "  CA      : $OUT/animo-ca.crt（已嵌入 App）"
echo "  证书    : $OUT/server.crt（SAN: IP:$IP）"
echo "  私钥    : $OUT/server.key（只放服务器，勿提交）"
echo "  Caddyfile: $ROOT/Backend/Caddyfile.ip"
echo
echo "服务器上启动："
echo "  cd Backend"
echo "  HTTPS_PORT=$PORT docker compose --profile ip-https up -d --build"
echo
echo "本机验证（把证书换到服务器路径）："
echo "  curl --cacert Backend/certs/animo-ca.crt $ADDR/health"
